//! The sandbox's environment variables and `env.sh`, the file every command re-sources.

use std::collections::BTreeMap;
use std::path::{Path, PathBuf};

use serde_json::Value;

use super::Ctx;

/// Variables owned by the sandbox, or meaningless outside the Nix build.
/// They are dropped from the dev shell and cannot be set by the repository policy.
const RESERVED: &[&str] = &[
    "HOME",
    "TMP",
    "TMPDIR",
    "TEMP",
    "TEMPDIR",
    "NIX_BUILD_TOP",
    "TERM",
    "USER",
    "LOGNAME",
    "PWD",
    "OLDPWD",
    "SHLVL",
    "_",
    "http_proxy",
    "https_proxy",
    "HTTP_PROXY",
    "HTTPS_PROXY",
    "ALL_PROXY",
    "all_proxy",
    "NO_PROXY",
    "no_proxy",
    "BASH_ENV",
    "ENV",
    "ZDOTDIR",
    "CLAUDE_ENV_FILE",
];

fn is_reserved(name: &str) -> bool {
    RESERVED.contains(&name)
}

/// The parts of `nix print-dev-env --json` that can be replayed in any POSIX shell.
#[derive(Clone, Debug, Default)]
pub struct DevEnv {
    pub vars: BTreeMap<String, String>,
    pub shell_hook: Option<String>,
}

impl DevEnv {
    pub fn parse(json: &Value) -> DevEnv {
        let mut dev = DevEnv::default();
        let variables = json["variables"].as_object().into_iter().flatten();

        for (name, variable) in variables {
            let Some(value) = variable["value"].as_str() else {
                continue; // arrays and associative arrays are bash-only
            };

            if name == "shellHook" {
                if !value.trim().is_empty() {
                    dev.shell_hook = Some(value.to_owned());
                }
                continue;
            }

            if variable["type"] == "exported" && !is_reserved(name) {
                dev.vars.insert(name.clone(), value.to_owned());
            }
        }

        dev
    }
}

/// Variables the sandbox itself controls. They win over everything else.
fn managed_vars(ctx: &Ctx, dev_path: Option<&str>) -> Vec<(&'static str, String)> {
    let rundir = ctx.rundir_inside.display();
    let private = ctx.private_dir();
    let home = private.join("home").to_string_lossy().into_owned();
    let tmp = private.join("tmp").to_string_lossy().into_owned();
    let proxy = format!("http://127.0.0.1:{}", ctx.proxy_port);

    // The agentbox binary (MCP shim, hooks) goes last on PATH.
    let bin = ctx.exe_inside.parent().unwrap_or(Path::new("/"));
    let path = match dev_path {
        Some(dev_path) if !dev_path.is_empty() => format!("{dev_path}:{}", bin.display()),
        _ => bin.display().to_string(),
    };

    vec![
        ("PATH", path),
        ("HOME", home),
        ("TMPDIR", tmp.clone()),
        ("TMP", tmp.clone()),
        ("TEMP", tmp),
        ("USER", "agent".into()),
        ("http_proxy", proxy.clone()),
        ("https_proxy", proxy.clone()),
        ("HTTP_PROXY", proxy.clone()),
        ("HTTPS_PROXY", proxy),
        // Every command re-sources env.sh; that is how hot reload reaches the agent.
        ("BASH_ENV", format!("{rundir}/env.sh")),
        ("ENV", format!("{rundir}/env.sh")),
        ("ZDOTDIR", format!("{rundir}/zdotdir")),
        ("CLAUDE_ENV_FILE", format!("{rundir}/claude-env")),
        ("AGENTBOX_SOCK", format!("{rundir}/agent.sock")),
        ("AGENTBOX_HOOK_SOCK", format!("{rundir}/hook.sock")),
    ]
}

/// Full environment of the sandbox, in increasing priority:
/// the dev shell, the repository policy's `env`, then sandbox-managed variables.
pub fn env_vars(dev: &DevEnv, ctx: &Ctx) -> BTreeMap<String, String> {
    let mut vars = dev.vars.clone();

    let workdir = ctx.workdir.to_string_lossy();
    for (name, value) in &ctx.policy.env {
        if is_reserved(name) || name == "PATH" {
            continue;
        }

        vars.insert(name.clone(), value.replace("$WORKDIR", &workdir));
    }

    let dev_path = dev.vars.get("PATH").map(String::as_str);
    for (name, value) in managed_vars(ctx, dev_path) {
        vars.insert(name.to_owned(), value);
    }

    vars
}

/// Quotes a value for a POSIX shell. Values with NUL bytes cannot be exported at all.
fn quote(value: &str) -> String {
    match shlex::try_quote(value) {
        Ok(quoted) => quoted.into_owned(),
        Err(_) => "''".to_owned(),
    }
}

/// Renders env.sh. Only POSIX `export`s, so bash, zsh and sh can all source it.
pub fn env_sh(vars: &BTreeMap<String, String>, shell_hook: Option<&str>) -> String {
    let mut script = String::from("# Generated by agentbox; replaced atomically on reload.\n");

    for (name, value) in vars {
        script += &format!("export {name}={}\n", quote(value));
    }

    // shellHook runs before every command, so it is expected to be cheap and idempotent.
    // It is bash code; other shells skip it.
    if let Some(hook) = shell_hook {
        let hook = quote(hook);
        script += &format!("if [ -n \"${{BASH_VERSION:-}}\" ]; then eval {hook} || true; fi\n");
    }

    script
}

/// Finds an executable the way execvp would, given a PATH value.
/// Names containing a slash are resolved relative to `cwd`.
pub fn resolve_in_path(path_var: &str, name: &str, cwd: &Path) -> Option<PathBuf> {
    which::which_in(name, Some(path_var), cwd).ok()
}

#[cfg(test)]
mod tests {
    use serde_json::json;

    use super::*;
    use crate::config::Config;
    use crate::sandbox::testing::{policy, with_ctx};

    #[test]
    fn env_is_layered_and_quoted() {
        let dev = DevEnv::parse(&json!({ "variables": {
            "PATH": { "type": "exported", "value": "/nix/store/x/bin" },
            "HOME": { "type": "exported", "value": "/homeless-shelter" },
            "internal": { "type": "var", "value": "x" },
            "shellHook": { "type": "var", "value": "echo hi" },
        }}));
        let policy = policy(true);
        let cfg = Config::default();

        let vars = with_ctx(&policy, &cfg, |ctx| env_vars(&dev, ctx));

        assert_eq!(vars["PATH"], "/nix/store/x/bin:/run/agentbox-bin");
        assert_eq!(vars["HOME"], "/w/it's/.agentbox/home");
        assert_eq!(vars["CARGO_HOME"], "/w/it's/.cache/cargo");
        assert!(!vars.contains_key("internal"));

        // Whatever quoting style is used, a shell must read the values back unchanged.
        let script = env_sh(&vars, dev.shell_hook.as_deref());
        let words: Vec<String> = script.lines().filter_map(shlex::split).flatten().collect();

        assert!(words.contains(&"HOME=/w/it's/.agentbox/home".to_string()));
        assert!(words.windows(2).any(|pair| pair == ["eval", "echo hi"]));
    }
}
