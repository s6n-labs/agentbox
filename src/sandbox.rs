//! Isolation backends (bubblewrap, Seatbelt), environment indirection and agent adapters.
//! Everything here is a pure function of its inputs so it can be tested on any platform.

use std::collections::BTreeMap;
use std::path::{Path, PathBuf};

use serde_json::{Value, json};

use crate::config::Config;
use crate::policy::Policy;

/// Port of the in-sandbox TCP→Unix bridge to the proxy (Linux, private network namespace).
pub const BRIDGE_PORT: u16 = 3128;

pub struct Ctx<'a> {
    pub workdir: &'a Path,
    /// Per-run directory on the host: env.sh, sockets, shell rc files.
    pub rundir: &'a Path,
    /// Where the sandbox sees `rundir` and the agentbox binary.
    pub rundir_inside: &'a Path,
    pub exe: &'a Path,
    pub exe_inside: &'a Path,
    /// Effective policy.
    pub policy: &'a Policy,
    pub cfg: &'a Config,
    pub proxy_port: u16,
    /// Writable directories already opened without following symlinks (path → fd
    /// inherited by bwrap). The agent controls these paths, so they are bound by fd.
    pub pinned: &'a BTreeMap<PathBuf, i32>,
}

impl Ctx<'_> {
    /// HOME and TMPDIR are recreated here.
    pub fn private_dir(&self) -> PathBuf {
        self.workdir.join(".agentbox")
    }
}

/// The parts of `nix print-dev-env --json` that are safe to replay in any POSIX shell.
#[derive(Clone, Debug, Default)]
pub struct DevEnv {
    pub vars: BTreeMap<String, String>,
    pub shell_hook: Option<String>,
}

/// Variables owned by the sandbox or meaningless outside the Nix build.
const DROPPED: &[&str] = &[
    "HOME",
    "TMP",
    "TMPDIR",
    "TEMP",
    "TEMPDIR",
    "NIX_BUILD_TOP",
    "TERM",
    "USER",
    "LOGNAME",
    "PWD",
    "OLDPWD",
    "SHLVL",
    "_",
    "http_proxy",
    "https_proxy",
    "HTTP_PROXY",
    "HTTPS_PROXY",
    "ALL_PROXY",
    "all_proxy",
    "NO_PROXY",
    "no_proxy",
    "BASH_ENV",
    "ENV",
    "ZDOTDIR",
    "CLAUDE_ENV_FILE",
];

impl DevEnv {
    pub fn parse(v: &Value) -> DevEnv {
        let mut dev = DevEnv::default();
        for (k, var) in v["variables"].as_object().into_iter().flatten() {
            let Some(val) = var["value"].as_str() else {
                continue;
            };
            if k == "shellHook" && !val.trim().is_empty() {
                dev.shell_hook = Some(val.to_owned());
            } else if var["type"] == "exported" && !DROPPED.contains(&k.as_str()) {
                dev.vars.insert(k.clone(), val.to_owned());
            }
        }
        dev
    }
}

/// Full environment of the sandbox: dev shell, then repo policy env, then sandbox-managed variables.
pub fn env_vars(dev: &DevEnv, ctx: &Ctx) -> BTreeMap<String, String> {
    let mut vars = dev.vars.clone();
    let workdir = ctx.workdir.to_string_lossy();
    for (k, v) in &ctx.policy.env {
        if !DROPPED.contains(&k.as_str()) && k != "PATH" {
            vars.insert(k.clone(), v.replace("$WORKDIR", &workdir));
        }
    }
    let rd = ctx.rundir_inside.display();
    let private = ctx.private_dir();
    let tmp = private.join("tmp").to_string_lossy().into_owned();
    let proxy = format!("http://127.0.0.1:{}", ctx.proxy_port);
    let bin = ctx
        .exe_inside
        .parent()
        .unwrap_or(Path::new("/"))
        .display()
        .to_string();
    let path = match vars.get("PATH") {
        Some(p) if !p.is_empty() => format!("{p}:{bin}"),
        _ => bin,
    };
    let managed = [
        ("PATH", path),
        ("HOME", private.join("home").to_string_lossy().into_owned()),
        ("TMPDIR", tmp.clone()),
        ("TMP", tmp.clone()),
        ("TEMP", tmp),
        ("USER", "agent".into()),
        ("http_proxy", proxy.clone()),
        ("https_proxy", proxy.clone()),
        ("HTTP_PROXY", proxy.clone()),
        ("HTTPS_PROXY", proxy),
        // Every command re-sources env.sh, which is how hot reload reaches the agent.
        ("BASH_ENV", format!("{rd}/env.sh")),
        ("ENV", format!("{rd}/env.sh")),
        ("ZDOTDIR", format!("{rd}/zdotdir")),
        ("CLAUDE_ENV_FILE", format!("{rd}/claude-env")),
        ("AGENTBOX_SOCK", format!("{rd}/agent.sock")),
        ("AGENTBOX_HOOK_SOCK", format!("{rd}/hook.sock")),
    ];
    vars.extend(managed.map(|(k, v)| (k.to_owned(), v)));
    vars
}

/// Quotes a value for a POSIX shell. Values with NUL bytes cannot be exported at all.
fn sh_quote(value: &str) -> String {
    shlex::try_quote(value)
        .map(|quoted| quoted.into_owned())
        .unwrap_or_else(|_| "''".to_owned())
}

/// Renders env.sh. POSIX exports only, so bash, zsh and sh can all source it.
pub fn env_sh(vars: &BTreeMap<String, String>, shell_hook: Option<&str>) -> String {
    let mut out = String::from("# Generated by agentbox; replaced atomically on reload.\n");
    for (k, v) in vars {
        out += &format!("export {k}={}\n", sh_quote(v));
    }
    if let Some(hook) = shell_hook {
        // shellHook runs before every command: it is expected to be cheap and idempotent.
        out += &format!(
            "if [ -n \"${{BASH_VERSION:-}}\" ]; then eval {} || true; fi\n",
            sh_quote(hook)
        );
    }
    out
}

/// Finds an executable the way execvp would, given a PATH value.
/// Names containing a slash are resolved relative to `cwd`.
pub fn resolve_in_path(path_var: &str, name: &str, cwd: &Path) -> Option<PathBuf> {
    which::which_in(name, Some(path_var), cwd).ok()
}

/// Agents we know how to wire up (MCP server, turn hooks, resume).
pub fn is_agent(argv: &[String]) -> bool {
    Path::new(&argv[0])
        .file_name()
        .is_some_and(|n| n == "claude")
}

/// Adapter layer: adds the MCP server and turn hooks, and resumes the session after a restart.
pub fn adapt_argv(argv: &[String], exe_inside: &Path, resume: Option<&str>) -> Vec<String> {
    let mut v = argv.to_vec();
    if !is_agent(argv) {
        return v;
    }
    let exe = exe_inside.to_string_lossy();
    let hook = |state: &str| json!([{ "hooks": [{ "type": "command", "command": format!("{exe} hook {state}") }] }]);
    v.extend([
        "--mcp-config".into(),
        json!({ "mcpServers": { "agentbox": { "command": exe, "args": ["mcp"] } } }).to_string(),
        "--settings".into(),
        json!({ "hooks": { "UserPromptSubmit": hook("busy"), "Stop": hook("idle") } }).to_string(),
    ]);
    if let Some(message) = resume {
        v.extend(["--continue".into(), message.into()]);
    }
    v
}

fn s(p: &Path) -> String {
    p.to_string_lossy().into_owned()
}

/// bubblewrap arguments up to and including `--`; the command follows.
pub fn bwrap_args(ctx: &Ctx, path_var: &str) -> Vec<String> {
    let covered = |p: &str| {
        ctx.cfg
            .fs
            .readonly
            .iter()
            .chain(&ctx.cfg.fs.writable)
            .any(|h| Path::new(p).starts_with(h))
    };
    let w = s(ctx.workdir);
    let mut a: Vec<String> = [
        "--die-with-parent",
        "--unshare-pid",
        "--unshare-net",
        "--unshare-ipc",
        "--unshare-uts",
        "--proc",
        "/proc",
        "--dev",
        "/dev",
        "--tmpfs",
        "/tmp",
        // ponytail: the whole store is listable on Linux; hiding names needs per-closure
        // binds (strict mode), which would make every env change a restart.
        "--ro-bind-try",
        "/nix/store",
        "/nix/store",
    ]
    .map(String::from)
    .to_vec();
    for p in &ctx.cfg.fs.readonly {
        a.extend(["--ro-bind".into(), s(p), s(p)]);
    }
    for p in &ctx.cfg.fs.writable {
        a.extend(["--bind".into(), s(p), s(p)]);
    }
    let bind = if ctx.policy.fs.workdir_writable {
        "--bind"
    } else {
        "--ro-bind"
    };
    a.extend([bind.into(), w.clone(), w.clone()]);
    let writable = ctx
        .policy
        .fs
        .writable
        .iter()
        .map(|rel| ctx.workdir.join(rel));
    for p in writable.chain([ctx.private_dir()]) {
        match ctx.pinned.get(&p) {
            Some(fd) => a.extend(["--bind-fd".into(), fd.to_string(), s(&p)]),
            None => a.extend(["--bind".into(), s(&p), s(&p)]),
        }
    }
    a.extend(["--ro-bind".into(), s(ctx.rundir), s(ctx.rundir_inside)]);
    a.extend(["--ro-bind".into(), s(ctx.exe), s(ctx.exe_inside)]);
    if !covered("/etc") {
        a.extend([
            "--ro-bind".into(),
            s(&ctx.rundir.join("passwd")),
            "/etc/passwd".into(),
        ]);
    }
    // Scripts expect these two even on NixOS.
    for (name, dir) in [("sh", "/bin"), ("env", "/usr/bin")] {
        if !covered(dir)
            && let Some(target) = resolve_in_path(path_var, name, ctx.workdir)
        {
            a.extend(["--symlink".into(), s(&target), format!("{dir}/{name}")]);
        }
    }
    a.extend(["--chdir".into(), w, "--".into()]);
    a
}

fn sb_str(p: &str) -> String {
    format!("\"{}\"", p.replace('\\', "\\\\").replace('"', "\\\""))
}

/// Seatbelt (SBPL) profile for macOS.
// ponytail: the system paths and Mach services below are a starting point taken from
// Nix's sandbox-defaults.sb; they still need to be validated on a real Mac.
pub fn seatbelt_profile(ctx: &Ctx) -> String {
    let sub = |p: &Path| format!("(subpath {})", sb_str(&p.to_string_lossy()));
    let workdir = sub(ctx.workdir);
    let private = sub(&ctx.private_dir());
    let rundir = sub(ctx.rundir_inside);
    let exe = format!("(literal {})", sb_str(&ctx.exe_inside.to_string_lossy()));
    let agent_sock = sb_str(&ctx.rundir_inside.join("agent.sock").to_string_lossy());
    let hook_sock = sb_str(&ctx.rundir_inside.join("hook.sock").to_string_lossy());
    let port = ctx.proxy_port;
    let mut p = format!(
        r#"(version 1)
(deny default)
(allow process-fork)
(allow signal (target same-sandbox))
(allow sysctl-read)
(allow pseudo-tty)

; Path traversal only; no directory listings outside the rules below.
(allow file-read-metadata)

; Nix store: every path is reachable by name, but the store itself cannot be listed.
(allow file-read* file-map-executable process-exec (subpath "/nix/store"))
(deny file-read-data (literal "/nix/store"))
(deny file-read* file-map-executable process-exec (subpath "/nix/store/.links"))
(deny file-read* file-write* (subpath "/nix/var/nix"))

; Minimum the dynamic linker and libSystem need.
(allow file-read* file-map-executable
  (subpath "/usr/lib")
  (subpath "/System/Library")
  (subpath "/System/Cryptexes")
  (subpath "/System/Volumes/Preboot/Cryptexes")
  (subpath "/private/var/db/timezone")
  (subpath "/usr/share/zoneinfo")
  (subpath "/usr/share/locale")
  (literal "/private/etc/localtime")
  (literal "/private/etc/passwd")
  (literal "/private/etc/protocols")
  (literal "/private/etc/services")
  (literal "/dev/dtracehelper"))
(allow file-read* file-write* file-ioctl
  (literal "/dev/null") (literal "/dev/zero") (literal "/dev/tty")
  (literal "/dev/random") (literal "/dev/urandom")
  (regex #"^/dev/ttys[0-9]+$") (regex #"^/dev/fd/[0-9]+$"))
(deny file-read* file-write* (subpath "/Users") (subpath "/private/var/folders"))

; Workdir, sandbox-managed HOME/TMPDIR and the read-only run directory.
(allow file-read* file-map-executable process-exec {workdir})
(allow file-write* {private})
(allow file-read* {rundir})
(allow file-read* file-map-executable process-exec {exe})

; Network: only the local proxy and the agent sockets. No DNS (mDNSResponder) either.
(allow network-outbound (remote tcp "localhost:{port}"))
(allow network-outbound (literal {agent_sock}) (literal {hook_sock}))

; Mach services are denied by default so nothing can be delegated to launchd/XPC.
(allow mach-lookup
  (global-name "com.apple.system.notification_center")
  (global-name "com.apple.system.opendirectoryd.libinfo")
  (global-name "com.apple.system.logger")
  (global-name "com.apple.logd"))
"#
    );
    if ctx.policy.fs.workdir_writable {
        p += &format!("(allow file-write* {workdir})\n");
    }
    for rel in &ctx.policy.fs.writable {
        p += &format!("(allow file-write* {})\n", sub(&ctx.workdir.join(rel)));
    }
    for host in &ctx.cfg.fs.readonly {
        p += &format!(
            "(allow file-read* file-map-executable process-exec {})\n",
            sub(host)
        );
    }
    for host in &ctx.cfg.fs.writable {
        p += &format!(
            "(allow file-read* file-write* file-map-executable process-exec {})\n",
            sub(host)
        );
    }
    for cap in &ctx.policy.capabilities {
        // Capabilities are names in the repo; their expansion lives only here.
        if cap == "xcode" {
            p += r#"; capability: xcode
(allow file-read* file-map-executable process-exec
  (subpath "/Applications/Xcode.app")
  (subpath "/Library/Developer")
  (literal "/usr/bin/xcrun") (literal "/usr/bin/xcode-select"))
(allow file-read* (subpath "/private/var/db/xcode_select_link"))
"#;
        }
    }
    if !ctx.cfg.seatbelt.extra.is_empty() {
        p += &format!("; host layer\n{}\n", ctx.cfg.seatbelt.extra);
    }
    p
}

#[cfg(test)]
mod tests {
    use super::*;

    fn policy(workdir_writable: bool) -> Policy {
        Policy::parse(&json!({
            "version": 1,
            "network": { "allow": [] },
            "fs": { "writable": ["target"], "workdirWritable": workdir_writable },
            "capabilities": ["xcode"],
            "env": { "CARGO_HOME": "$WORKDIR/.cache/cargo", "HOME": "/evil", "PATH": "/evil" },
        }))
        .unwrap()
    }

    fn with_ctx<T>(policy: &Policy, cfg: &Config, f: impl FnOnce(&Ctx) -> T) -> T {
        f(&Ctx {
            workdir: Path::new("/w/it's"),
            rundir: Path::new("/state/runs/r1"),
            rundir_inside: Path::new("/run/agentbox"),
            exe: Path::new("/host/agentbox"),
            exe_inside: Path::new("/run/agentbox-bin/agentbox"),
            policy,
            cfg,
            proxy_port: 3128,
            pinned: &BTreeMap::from([(PathBuf::from("/w/it's/.agentbox"), 7)]),
        })
    }

    #[test]
    fn env_is_layered_and_quoted() {
        let dev = DevEnv::parse(&json!({ "variables": {
            "PATH": { "type": "exported", "value": "/nix/store/x/bin" },
            "HOME": { "type": "exported", "value": "/homeless-shelter" },
            "internal": { "type": "var", "value": "x" },
            "shellHook": { "type": "var", "value": "echo hi" },
        }}));
        let (p, cfg) = (policy(true), Config::default());
        let vars = with_ctx(&p, &cfg, |ctx| env_vars(&dev, ctx));
        assert_eq!(vars["PATH"], "/nix/store/x/bin:/run/agentbox-bin");
        assert_eq!(vars["HOME"], "/w/it's/.agentbox/home");
        assert_eq!(vars["CARGO_HOME"], "/w/it's/.cache/cargo");
        assert!(!vars.contains_key("internal"));
        let sh = env_sh(&vars, dev.shell_hook.as_deref());

        // Whatever quoting style is used, a shell must read the values back unchanged.
        let words: Vec<String> = sh.lines().filter_map(shlex::split).flatten().collect();
        assert!(words.contains(&"HOME=/w/it's/.agentbox/home".to_string()));
        assert!(words.windows(2).any(|pair| pair == ["eval", "echo hi"]));
    }

    #[test]
    fn bwrap_respects_policy() {
        let (p, cfg) = (policy(false), Config::default());
        let args = with_ctx(&p, &cfg, |ctx| bwrap_args(ctx, "")).join(" ");
        assert!(args.contains("--unshare-net"));
        assert!(args.contains("--ro-bind /w/it's /w/it's --bind /w/it's/target /w/it's/target"));
        assert!(args.contains("--ro-bind /state/runs/r1 /run/agentbox"));
        assert!(args.contains("--bind-fd 7 /w/it's/.agentbox"));
        assert!(!args.contains("/home"));
    }

    #[test]
    fn seatbelt_respects_policy() {
        let (p, mut cfg) = (policy(false), Config::default());
        cfg.seatbelt.extra = "(allow mach-lookup (global-name \"x\"))".into();
        let sb = with_ctx(&p, &cfg, seatbelt_profile);
        assert!(sb.starts_with("(version 1)\n(deny default)"));
        assert!(sb.contains("(deny file-read-data (literal \"/nix/store\"))"));
        assert!(sb.contains("(remote tcp \"localhost:3128\")"));
        assert!(sb.contains("(allow file-write* (subpath \"/w/it's/target\"))"));
        assert!(!sb.contains("(allow file-write* (subpath \"/w/it's\"))"));
        assert!(sb.contains("/Applications/Xcode.app"));
        assert!(sb.ends_with("(allow mach-lookup (global-name \"x\"))\n"));
    }

    #[test]
    fn claude_gets_mcp_hooks_and_resume() {
        let argv = vec!["claude".to_string()];
        let v = adapt_argv(&argv, Path::new("/bin/agentbox"), Some("env updated"));
        assert!(v.contains(&"--mcp-config".to_string()) && v.contains(&"--settings".to_string()));
        assert_eq!(&v[v.len() - 2..], ["--continue", "env updated"]);
        let sh = vec!["zsh".to_string()];
        assert_eq!(adapt_argv(&sh, Path::new("/bin/agentbox"), None), sh);
    }
}
